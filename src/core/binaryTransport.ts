// Base64 helpers for chrome.runtime.sendMessage transport. JSON messages
// can't carry Blob/ArrayBuffer; we encode bytes as base64 on one side and
// rebuild a Uint8Array on the other (request bodies in http.ts, response
// bodies in background/index.ts).

export function bytesToBase64(bytes: Uint8Array): string {
  let binary = ''
  const CHUNK = 0x8000
  for (let i = 0; i < bytes.length; i += CHUNK) {
    binary += String.fromCharCode.apply(null, Array.from(bytes.subarray(i, i + CHUNK)) as unknown as number[])
  }
  return btoa(binary)
}

export function base64ToBytes(b64: string): Uint8Array {
  const binary = atob(b64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return bytes
}
